-- 09_kopis_performances.sql : 샘플 공연 25편(work_id 81~105)과 연결 데이터를 지우고 KOPIS 실제 공연 25편으로 바꾼다 (2026-11-16)
-- 지우는 것: 샘플 공연, 그 공연의 감상 기록·후기·좋아요·댓글·컬렉션 항목·인물(다른 작품에 안 쓰인 것)
-- 넣는 것: KOPIS 예매 순위(2026-11-01~15) 장르별 상위 공연 — 뮤지컬 12, 연극 10, 무용 3 (같은 작품의 지역 공연은 하나만)
--          work(source='KOPIS', external_id=공연ID) + performance + work_genre + person/work_person(출연 최대 8, 제작진 최대 4)
-- 작품 번호 81~105 는 그대로 다시 쓴다. 인물 번호는 1001부터.
-- 공연 정보 출처: (재)예술경영지원센터 공연예술통합전산망(www.kopis.or.kr)

SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

DELETE FROM review_like WHERE review_id IN (SELECT v.review_id FROM review v JOIN record r ON r.record_id = v.record_id WHERE r.work_id BETWEEN 81 AND 105);
DELETE FROM comments WHERE review_id IN (SELECT v.review_id FROM review v JOIN record r ON r.record_id = v.record_id WHERE r.work_id BETWEEN 81 AND 105);
DELETE FROM review WHERE record_id IN (SELECT record_id FROM record WHERE work_id BETWEEN 81 AND 105);
DELETE FROM record WHERE work_id BETWEEN 81 AND 105;
DELETE FROM collection_item WHERE work_id BETWEEN 81 AND 105;
DELETE FROM person WHERE person_id IN (SELECT person_id FROM work_person WHERE work_id BETWEEN 81 AND 105)
  AND person_id NOT IN (SELECT person_id FROM work_person WHERE work_id NOT BETWEEN 81 AND 105);
-- performance, work_genre, work_person 은 work 를 지우면 ON DELETE CASCADE 로 함께 지워진다
DELETE FROM work WHERE work_id BETWEEN 81 AND 105 AND type = 'PERFORMANCE';

