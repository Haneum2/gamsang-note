-- ============================================================
-- 01_schema.sql : 작품 기록 & 후기 공유 앱 (감상노트) - Oracle 테이블 생성
-- 대상: Oracle Database 12.2 이상 (19c / 21c XE 권장)
-- 기준: 물리적 데이터 모델(MySQL 8) 문서를 Oracle 문법으로 변환
-- 위에서 아래로 한 번에 실행하면 된다. (부모 테이블 먼저)
-- ============================================================

-- 1. 회원
CREATE TABLE users (
  user_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  nickname    VARCHAR2(30 CHAR)  NOT NULL,
  email       VARCHAR2(255 CHAR) NOT NULL,
  created_at  TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_users PRIMARY KEY (user_id),
  CONSTRAINT uq_users_email UNIQUE (email)
);

-- 2. 친구 (USER 자기참조 N:M)
CREATE TABLE friendship (
  requester_id  NUMBER(10) NOT NULL,
  receiver_id   NUMBER(10) NOT NULL,
  status        VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
  requested_at  TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_friendship PRIMARY KEY (requester_id, receiver_id),
  CONSTRAINT fk_friendship_requester FOREIGN KEY (requester_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT fk_friendship_receiver FOREIGN KEY (receiver_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT ck_friendship_status CHECK (status IN ('PENDING', 'ACCEPTED')),
  CONSTRAINT ck_friendship_not_self CHECK (requester_id <> receiver_id)
);

-- 3. 작품 (슈퍼타입)
CREATE TABLE work (
  work_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  type          VARCHAR2(12) NOT NULL,
  title         VARCHAR2(200 CHAR) NOT NULL,
  release_date  DATE NULL,
  summary       CLOB NULL,
  poster_url    VARCHAR2(500) NULL,
  CONSTRAINT pk_work PRIMARY KEY (work_id),
  CONSTRAINT ck_work_type CHECK (type IN ('MOVIE', 'BOOK', 'PERFORMANCE'))
);

-- 4. 작품 서브타입 (기본키 = 슈퍼타입 WORK의 외래키)
CREATE TABLE movie (
  work_id  NUMBER(10) NOT NULL,
  runtime  NUMBER(5) NULL,
  CONSTRAINT pk_movie PRIMARY KEY (work_id),
  CONSTRAINT fk_movie_work FOREIGN KEY (work_id)
    REFERENCES work (work_id) ON DELETE CASCADE,
  CONSTRAINT ck_movie_runtime CHECK (runtime IS NULL OR runtime > 0)
);

CREATE TABLE book (
  work_id  NUMBER(10) NOT NULL,
  isbn     VARCHAR2(20) NULL,
  pages    NUMBER(6) NULL,
  CONSTRAINT pk_book PRIMARY KEY (work_id),
  CONSTRAINT uq_book_isbn UNIQUE (isbn),
  CONSTRAINT fk_book_work FOREIGN KEY (work_id)
    REFERENCES work (work_id) ON DELETE CASCADE,
  CONSTRAINT ck_book_pages CHECK (pages IS NULL OR pages > 0)
);

CREATE TABLE performance (
  work_id  NUMBER(10) NOT NULL,
  venue    VARCHAR2(100 CHAR) NULL,
  period   VARCHAR2(100 CHAR) NULL,
  CONSTRAINT pk_performance PRIMARY KEY (work_id),
  CONSTRAINT fk_performance_work FOREIGN KEY (work_id)
    REFERENCES work (work_id) ON DELETE CASCADE
);

-- 5. 장르와 작품-장르 (N:M)
CREATE TABLE genre (
  genre_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  name      VARCHAR2(50 CHAR) NOT NULL,
  CONSTRAINT pk_genre PRIMARY KEY (genre_id),
  CONSTRAINT uq_genre_name UNIQUE (name)
);

CREATE TABLE work_genre (
  work_id   NUMBER(10) NOT NULL,
  genre_id  NUMBER(10) NOT NULL,
  CONSTRAINT pk_work_genre PRIMARY KEY (work_id, genre_id),
  CONSTRAINT fk_work_genre_work FOREIGN KEY (work_id)
    REFERENCES work (work_id) ON DELETE CASCADE,
  CONSTRAINT fk_work_genre_genre FOREIGN KEY (genre_id)
    REFERENCES genre (genre_id) ON DELETE CASCADE
);

-- 6. 인물과 작품-인물 (N:M, 역할 포함)
CREATE TABLE person (
  person_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  name       VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT pk_person PRIMARY KEY (person_id)
);

CREATE TABLE work_person (
  work_id    NUMBER(10) NOT NULL,
  person_id  NUMBER(10) NOT NULL,
  role       VARCHAR2(30 CHAR) NOT NULL,
  CONSTRAINT pk_work_person PRIMARY KEY (work_id, person_id, role),
  CONSTRAINT fk_work_person_work FOREIGN KEY (work_id)
    REFERENCES work (work_id) ON DELETE CASCADE,
  CONSTRAINT fk_work_person_person FOREIGN KEY (person_id)
    REFERENCES person (person_id) ON DELETE CASCADE
);

-- 7. 감상 기록 (사용자당 작품 1건)
--    work_id FK는 ON DELETE 절을 생략한다. Oracle의 기본 동작(NO ACTION)이
--    MySQL의 RESTRICT와 같아서, 기록이 있는 작품은 삭제할 수 없다.
CREATE TABLE record (
  record_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  user_id       NUMBER(10) NOT NULL,
  work_id       NUMBER(10) NOT NULL,
  status        VARCHAR2(10) DEFAULT 'WANT' NOT NULL,
  rating        NUMBER(2,1) NULL,
  watched_date  DATE NULL,
  CONSTRAINT pk_record PRIMARY KEY (record_id),
  CONSTRAINT uq_record_user_work UNIQUE (user_id, work_id),
  CONSTRAINT fk_record_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT fk_record_work FOREIGN KEY (work_id)
    REFERENCES work (work_id),
  CONSTRAINT ck_record_status CHECK (status IN ('WANT', 'WATCHING', 'DONE')),
  CONSTRAINT ck_record_rating CHECK (
    rating IS NULL OR (rating BETWEEN 0.5 AND 5.0 AND MOD(rating * 10, 5) = 0)
  )
);

-- 8. 후기
CREATE TABLE review (
  review_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  record_id    NUMBER(10) NOT NULL,
  content      CLOB NOT NULL,
  spoiler_yn   CHAR(1) DEFAULT 'N' NOT NULL,
  visibility   VARCHAR2(10) DEFAULT 'PRIVATE' NOT NULL,
  created_at   TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_review PRIMARY KEY (review_id),
  CONSTRAINT fk_review_record FOREIGN KEY (record_id)
    REFERENCES record (record_id) ON DELETE CASCADE,
  CONSTRAINT ck_review_spoiler CHECK (spoiler_yn IN ('Y', 'N')),
  CONSTRAINT ck_review_visibility CHECK (visibility IN ('ALL', 'FRIEND', 'PRIVATE'))
);

-- 9. 좋아요 (USER-REVIEW N:M)
CREATE TABLE review_like (
  review_id   NUMBER(10) NOT NULL,
  user_id     NUMBER(10) NOT NULL,
  created_at  TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_review_like PRIMARY KEY (review_id, user_id),
  CONSTRAINT fk_review_like_review FOREIGN KEY (review_id)
    REFERENCES review (review_id) ON DELETE CASCADE,
  CONSTRAINT fk_review_like_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE
);

-- 10. 댓글
CREATE TABLE comments (
  comment_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  review_id   NUMBER(10) NOT NULL,
  user_id     NUMBER(10) NOT NULL,
  content     CLOB NOT NULL,
  created_at  TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_comments PRIMARY KEY (comment_id),
  CONSTRAINT fk_comments_review FOREIGN KEY (review_id)
    REFERENCES review (review_id) ON DELETE CASCADE,
  CONSTRAINT fk_comments_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE
);

-- 11. 컬렉션과 컬렉션-작품 (N:M)
CREATE TABLE collection (
  collection_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  user_id        NUMBER(10) NOT NULL,
  title          VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT pk_collection PRIMARY KEY (collection_id),
  CONSTRAINT fk_collection_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE collection_item (
  collection_id  NUMBER(10) NOT NULL,
  work_id        NUMBER(10) NOT NULL,
  CONSTRAINT pk_collection_item PRIMARY KEY (collection_id, work_id),
  CONSTRAINT fk_collection_item_collection FOREIGN KEY (collection_id)
    REFERENCES collection (collection_id) ON DELETE CASCADE,
  CONSTRAINT fk_collection_item_work FOREIGN KEY (work_id)
    REFERENCES work (work_id) ON DELETE CASCADE
);

-- ============================================================
-- 인덱스 (Oracle은 MySQL과 달리 외래키 인덱스를 자동으로 만들지 않으므로 명시)
-- 기본키·UNIQUE 제약은 인덱스가 자동 생성된다.
-- ============================================================
CREATE INDEX idx_work_type_title       ON work (type, title);
CREATE INDEX idx_person_name           ON person (name);
CREATE INDEX idx_friendship_receiver   ON friendship (receiver_id);
CREATE INDEX idx_work_genre_genre      ON work_genre (genre_id);
CREATE INDEX idx_work_person_person    ON work_person (person_id);
CREATE INDEX idx_record_work           ON record (work_id);
CREATE INDEX idx_record_user_watched   ON record (user_id, watched_date);
CREATE INDEX idx_review_record         ON review (record_id);
CREATE INDEX idx_review_created        ON review (created_at);
CREATE INDEX idx_review_like_user      ON review_like (user_id);
CREATE INDEX idx_comments_review       ON comments (review_id, created_at);
CREATE INDEX idx_comments_user         ON comments (user_id);
CREATE INDEX idx_collection_user       ON collection (user_id);
CREATE INDEX idx_collection_item_work  ON collection_item (work_id);

-- 친구 중복 방지(양방향): (1,2)가 있으면 (2,1)도 막는다.
-- 기본키는 같은 방향의 중복만 막으므로, 작은 번호/큰 번호 쌍에 유일 인덱스를 둔다.
-- MySQL 문서에서는 트리거로 처리했지만, Oracle은 트리거에서 같은 테이블을 조회하면
-- 변경 중 테이블 오류(ORA-04091)가 날 수 있어 함수 기반 유일 인덱스로 대체했다.
CREATE UNIQUE INDEX uq_friendship_pair
  ON friendship (LEAST(requester_id, receiver_id), GREATEST(requester_id, receiver_id));
